// Produce a dependency-free lazy CommonJS bundle for the installed DSH module loader.
// Only React is a platform external; the shared daemon API catalog is data at build time.
import { readFile, writeFile } from 'node:fs/promises';
import { REMOTE_PACKAGE, REMOTE_NAMESPACE, REMOTE_METHODS, TOPICS, WIKI_SCOPES } from '../host/remote-contract.mjs';

const path = name => new URL(name, import.meta.url);
const source = await Promise.all([
  'plugin.cjs', 'remote.cjs', 'live.cjs', 'i18n.cjs', 'cli-helper.cjs', 'views.cjs', 'workbench-store.cjs', 'workbench.cjs',
].map(async name =>
  JSON.stringify('./' + name) + ': (module, exports, require) => {\n' + await readFile(path(name), 'utf8') + '}'));
const contract = JSON.stringify({ REMOTE_PACKAGE, REMOTE_NAMESPACE, REMOTE_METHODS, TOPICS, WIKI_SCOPES });
const css = JSON.stringify(await readFile(path('style.css'), 'utf8'));
const artifact = `// Generated by client/build.mjs; do not edit.
window.__ModuleLoader__.load({ id: ${JSON.stringify(REMOTE_PACKAGE)}, factory: platformRequire => {
  'use strict';
  const modules = {
${source.join(',\n')}
  };
  const cache = Object.create(null);
  const load = name => {
    if (name === 'react') return platformRequire(name);
    if (name === './contract') return ${contract};
    if (name === './style') return ${css};
    if (!Object.hasOwn(modules, name)) throw new Error('Unexpected AI4Math module request: ' + name);
    if (!Object.hasOwn(cache, name)) {
      const module = { exports: {} };
      cache[name] = module;
      modules[name](module, module.exports, load);
    }
    return cache[name].exports;
  };
  return load('./plugin.cjs');
}});
`;

if (process.argv.includes('--check')) {
  if (await readFile(path('client.js'), 'utf8') !== artifact) {
    throw new Error('client/client.js is stale; run node plugins/dsh-ai4math/client/build.mjs');
  }
} else {
  await writeFile(path('client.js'), artifact, 'utf8');
}
